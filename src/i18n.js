let currentLanguage = "en";

function setLanguage(language) {
  if (language in TRANSLATIONS) currentLanguage = language;
}

function getLanguage() {
  return currentLanguage;
}

// A number of years as words, like "1 year" or "10 years", in the current language.
function formatYears(years) {
  return years === 1 ? t("form.yearsOne") : t("form.yearsOption", { years });
}

// Looks up a message in the current language (falling back to English) and fills in {placeholders}.
function t(key, params = {}) {
  const template = TRANSLATIONS[currentLanguage][key] ?? TRANSLATIONS.en[key] ?? key;
  return template.replace(/\{(\w+)\}/g, (placeholder, name) => (name in params ? String(params[name]) : placeholder));
}

